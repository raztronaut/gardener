// Optional full grid integration check; use external Playwright/browser.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright'),assert=require('assert');

(async()=>{const b=await chromium.launch({executablePath:process.env.GARDENER_TEST_BROWSER,args:['--no-sandbox','--disable-gpu','--disable-webgl']});
const p=await b.newPage({viewport:{width:900,height:1600}});
const errors=[];
p.on('pageerror',e=>errors.push(e.message));
await p.addInitScript(()=>localStorage.setItem('garden.retire.midterms',String(Date.now()-1)));
await p.goto((process.env.GARDENER_TEST_URL||'http://127.0.0.1:8787')+'/?theme=classic&screenshot=1',{waitUntil:'domcontentloaded'});
await p.waitForSelector('#garden[data-layout=standard]');
const act=async input=>{const r=await p.evaluate(input=>window.gardenWall.act({name:'layout',input}),input);
assert(r.ok,JSON.stringify(r));
return r;
};
const snap=()=>p.evaluate(()=>window.gardenWall.context().layout);
const positions=async()=>{const s=await snap();
return s.widgets.map(w=>({id:w.id,page:w.page,footprint:w.footprint.name,hidden:w.hidden,order:w.order}));
};
async function verify(){const count=(await snap()).pages;
for(let page=1;
page<=count;
page++){await act({action:'page',page});
const problems=await p.evaluate(()=>{const g=document.querySelector('#garden'),gr=g.getBoundingClientRect(),cards=[...g.querySelectorAll(':scope>.card:not(.widget-page-hidden)')],bad=[];
for(let i=0;
i<cards.length;
i++){const c=cards[i],r=c.getBoundingClientRect(),w=window.gardenWall.context().layout.widgets.find(w=>w.id===c.dataset.wid);
if(Math.abs(r.width-w.footprint.width)>1||Math.abs(r.height-w.footprint.height)>1)bad.push(c.dataset.wid+' footprint');
if(r.top<gr.top||r.bottom>gr.bottom||r.left<gr.left||r.right>gr.right)bad.push(c.dataset.wid+' outside');
for(let j=0;
j<i;
j++){const q=cards[j].getBoundingClientRect();
if(Math.min(q.right,r.right)-Math.max(q.left,r.left)>1&&Math.min(q.bottom,r.bottom)-Math.max(q.top,r.top)>1)bad.push('collision');
}}if(g.scrollHeight>g.clientHeight)bad.push('scroll');
return bad;
});
assert.deepEqual(problems,[]);
}}
await verify();
await act({action:'page',page:1});
const baseline=await positions();
const rejected=await p.evaluate(()=>window.gardenWall.act({name:'layout',input:{action:'resize',widget:'weather',size:'large',page:20}}));
assert(!rejected.ok);
assert.deepEqual(await positions(),baseline,'rejected action must restore all state');
assert.equal((await snap()).pages,2);
await act({action:'resize',widget:'weather',size:'wide'});
const resized=await positions();
assert(resized.some(w=>w.id!=='weather'&&w.page!==baseline.find(b=>b.id===w.id).page),'resize must spill peers');
await verify();
await act({action:'edit'});
await act({action:'done'});
assert.deepEqual(await positions(),resized,'edit/go must not repack');
await p.reload();
await p.waitForSelector('#garden[data-layout=standard]');
assert.deepEqual(await positions(),resized,'reload must preserve resize placement');
await act({action:'resize',widget:'weather',size:'original'});
assert.deepEqual(await positions(),baseline,'shrinking restores automatic overflow');
await act({action:'move',widget:'hacker-news',page:2});
await act({action:'resize',widget:'weather',size:'wide'});
await act({action:'resize',widget:'weather',size:'original'});
assert.equal((await snap()).widgets.find(w=>w.id==='hacker-news').page,2,'manual page choice survives auto packing');
await verify();
await act({action:'add_page'});
const count=(await snap()).pages;
await act({action:'remove_page',page:count});
assert.equal((await snap()).pages,count-1);
await act({action:'remove',widget:'air-quality'});
await act({action:'add',widget:'air-quality',page:1});
assert(!(await snap()).widgets.find(w=>w.id==='air-quality').hidden);
await act({action:'page',page:1});
await act({action:'edit'});
const c=p.locator('#garden>.card[data-wid="weather"]');
const box=await c.boundingBox();
await p.mouse.move(box.x+box.width/2,box.y+box.height/2);
await p.mouse.down();
assert(await p.locator('.home-drag-ghost').count(),'drag should start from content');
await p.mouse.up();
await act({action:'done'});
assert.deepEqual(errors,[]);
console.log('PASS: every page footprint/bounds/collision, overflow/restoration, manual page intent, edit/reload stability, add/remove/page actions, whole-card drag');
await b.close();
})().catch(e=>{console.error(e);
process.exit(1)});

