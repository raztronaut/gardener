"""Scripted paths from power-on to useful Super Bomberman 2 states.

    python3 paths.py            # build every state into data/sb2/states/ + scripts/
    python3 paths.py --check    # replay the emitted scripts from power-on, compare hashes
    python3 paths.py --multitap [--check]   # the *_mt states (Multitap in port 2)

Each path is driven by screen detection (PPU brightness / forced blank), and
every pad value fed to the emulator is logged; the log is written as a plain
input script (scripts/<name>.txt, committed) so the exact same state can be
rebuilt with `inputs.py scripts/battle_start.txt --save x.state` without any
detection logic. --check proves the scripts reproduce the states bit-exactly.

Menu navigation (measured 2026-10-25, USA ROM, see NOTES-harness.md):
  power-on -> Hudson/intro story -> START skips to title (cursor: NORMAL GAME)
  title: DOWN = BATTLE GAME, START
  battle: SINGLE MATCH / TAG MATCH  -> START (single)
  player table 1P..4P MAN/COM (default 1P MAN 2P MAN 3P COM 4P COM):
     DOWN moves the cursor, RIGHT toggles MAN/COM, START confirms
  rules: COM LEVEL 5, BATTLE 3, TIME 2:00, G-BOMBER ON (defaults) -> START
  stage select: STAGE 1..10 (LEFT/RIGHT, wraps), START
  arena fades in ~315 frames after START; input moves the bomber once the fade
  completes (brightness 15)
"""
import os
import sys
import hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from snes import Snes, B, STATES_DIR, DEBUG_DIR  # noqa: E402
import inputs  # noqa: E402

SCRIPTS = os.path.join(HERE, 'scripts')


class Rec:
    """Wraps Snes; logs every frame's pads so the path can be emitted as a script."""

    def __init__(self, S):
        self.S = S
        self.log = []

    def run(self, n, pads=0):
        for _ in range(n):
            self.S.step(pads)
            self.log.append(pads if isinstance(pads, tuple) else (pads,))

    def tap(self, button, hold=2, after=20):
        self.run(hold, button)
        self.run(after, 0)

    def wait(self, pred, maxf=3000, what='?'):
        for _ in range(maxf):
            if pred(self.S):
                return
            self.run(1)
        raise RuntimeError('timeout waiting for ' + what)

    def wait_fade_in(self, maxf=3000, what='fade-in'):
        """Wait for a dark phase (brightness 0 / forced blank) then full brightness."""
        self.wait(lambda S: S.ppu()['brightness'] == 0 or S.ppu()['forced_blank'], maxf, what + ' (dark)')
        self.wait(lambda S: S.ppu()['brightness'] == 15 and not S.ppu()['forced_blank'], maxf, what)

    def script(self):
        return inputs.to_text(self.log)


def bright(S, min_mean=20):
    p = S.ppu()
    return p['brightness'] == 15 and not p['forced_blank'] and S.frame().mean() > min_mean


def boot_to_title(R):
    # Fixed waits measured by stepping + looking at frames (debug/intro.png,
    # title.png). The intro story runs from power-on; START skips to the title.
    R.run(250)
    R.tap(B.START, 2, 410)        # title fully drawn ~f412, menu live


def title_to_battle_players(R):
    R.tap(B.DOWN, 1, 20)          # cursor -> BATTLE GAME
    R.tap(B.START, 1, 220)        # long black load, SINGLE/TAG menu fades in ~f190
    R.tap(B.START, 1, 120)        # SINGLE MATCH -> player table


def players_to_stage_select(R, humans=1):
    # default table: 1P MAN, 2P MAN, 3P COM, 4P COM
    if humans == 1:
        R.tap(B.DOWN, 1, 10)      # cursor -> 2P
        R.tap(B.RIGHT, 1, 10)     # 2P MAN -> COM
    R.tap(B.START, 1, 160)        # -> rules (COM LEVEL/BATTLE/TIME/G-BOMBER)
    R.tap(B.START, 1, 200)        # accept defaults -> stage select (preview drawn)


def stage_select_to_match(R, stage=1):
    for _ in range(stage - 1):
        R.tap(B.RIGHT, 1, 50)
    R.tap(B.START, 1, 200)        # fade out + load (screen black)
    R.wait(lambda S: bright(S), 600, 'arena fade-in')   # arena first fully bright


def title_to_normal(R):
    R.tap(B.START, 1, 700)        # NORMAL GAME: story, "1 - 1 START!" card
    R.wait(lambda S: bright(S, 60), 900, 'level 1-1 fade-in')


def build(multitap=False):
    """multitap=False: all single-pad states. multitap=True (separate process -
    one core per process): Multitap in port 2, 4 humans, states named *_mt."""
    os.makedirs(STATES_DIR, exist_ok=True)
    os.makedirs(SCRIPTS, exist_ok=True)
    S = Snes(multitap=multitap)
    power = S.save_state()
    made = {}

    def emit(name, R, png=True):
        path = os.path.join(STATES_DIR, name + '.state')
        S.save_state_file(path)
        with open(os.path.join(SCRIPTS, name + '.txt'), 'w') as f:
            f.write('# %s: from power-on, %d frames. Generated by paths.py; replay with\n'
                    '#   python3 inputs.py scripts/%s.txt%s --save out.state\n'
                    % (name, len(R.log), name, ' --multitap' if multitap else ''))
            f.write(R.script())
        if png:
            S.png(os.path.join(DEBUG_DIR, 'state_' + name + '.png'))
        made[name] = (len(R.log), S.wram_hash())
        print('%-20s frames=%6d wram=%s' % (name, len(R.log), made[name][1][:12]))

    # title
    S.load_state(power)
    R = Rec(S)
    boot_to_title(R)
    emit('title_mt' if multitap else 'title', R)
    title_log = list(R.log)
    title_state = S.save_state()

    if multitap:
        # with a Multitap present the player table defaults to 1P-4P all MAN
        title_to_battle_players(R)
        players_to_stage_select(R, humans=4)
        emit('stage_select_4p_mt', R)
        stage_select_to_match(R, 1)
        emit('battle_start_4p_mt', R)
        return made

    # normal game 1-1
    R = Rec(S); R.log = list(title_log); S.load_state(title_state)
    title_to_normal(R)
    emit('normal_1_1', R)

    # battle, 1 human + 3 COM and 2 humans + 2 COM
    for humans, suffix in ((1, ''), (2, '_2p')):
        R = Rec(S); R.log = list(title_log); S.load_state(title_state)
        title_to_battle_players(R)
        if humans == 1:
            emit('battle_players', R)
        players_to_stage_select(R, humans)
        emit('stage_select' + suffix, R)
        ss_log, ss_state = list(R.log), S.save_state()
        stages = range(1, 11) if humans == 1 else (1,)
        for st in stages:
            R = Rec(S); R.log = list(ss_log); S.load_state(ss_state)
            stage_select_to_match(R, st)
            emit('battle_stage%02d%s' % (st, suffix), R)
            if st == 1 and humans == 1:
                emit('battle_start', R, png=False)
    return made


def check(multitap=False):
    """Replay each emitted script from power-on in a fresh run; compare the full
    savestate with the saved .state file. *_mt scripts need --multitap."""
    S = Snes(multitap=multitap)
    power = S.save_state()
    ok = True
    for fn in sorted(os.listdir(SCRIPTS)):
        if not fn.endswith('.txt'):
            continue
        name = fn[:-4]
        if name.endswith('_mt') != multitap:
            continue
        S.load_state(power)
        inputs.play(S, open(os.path.join(SCRIPTS, fn)).read())
        mine = S.save_state()
        ref = open(os.path.join(STATES_DIR, name + '.state'), 'rb').read()
        same = hashlib.sha1(mine).digest() == hashlib.sha1(ref).digest()
        ok &= same
        print('%-20s %s' % (name, 'IDENTICAL state' if same else 'DIFFERENT'))
    return ok


if __name__ == '__main__':
    mt = '--multitap' in sys.argv
    if '--check' in sys.argv:
        sys.exit(0 if check(mt) else 1)
    build(mt)
