"""Runtime pack for the port's renderer (phase 3b) -> data/sb2/assets/pack/ (gitignored).

    python3 tools/sb2/extract/pack.py

Everything the browser needs at boot in two requests:
  pack/sb2.bin   concatenated blobs (offsets in pack.json)
  pack/pack.json manifest

Blobs (all raw, decoded by public/arcade/sb2/render/*.js):
  rom.<bank>   whole 64 KiB ROM banks the display code reads like the original does:
               $C1 (palettes: bomber colours, stage 8/9 cycles),
               $C2 (sprite poses: count + 5-byte OAM pieces, pointed to by object +79),
               $C5 (bomber pose graphics C5:0000.. streamed into VRAM by C09EDA, tables)
  stageNN      the PPU state at the first fully bright frame of a quiet 4-human match on
               stage NN (harness state mt4_stageNN, tools/sb2/extract/common.py):
               VRAM 64 KiB + CGRAM 512 B + WRAM $7E4000-$7E5FFF (8 KiB: the source
               graphics of the animated characters, $7E4828 + frame*32, C1340A)
  stageNN.ppu  PPU registers of that frame (in the JSON)

Requires the harness core and the derived states (tools/sb2/harness/build.sh, paths.py,
tools/sb2/extract/common.py). Never commit the output: it is derived from the ROM.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import Snes, ASSETS, NSTAGES, state_path, build_mt_stage_states, read_json  # noqa: E402

OUT = os.path.join(ASSETS, 'pack')
ROM_BANKS = [0xC1, 0xC2, 0xC5]
WRAM_SLICE = (0x4000, 0x6000)


def main():
    os.makedirs(OUT, exist_ok=True)
    build_mt_stage_states()
    S = Snes(multitap=True)
    rom = S.rom()
    blobs, index = [], {}
    off = 0

    def add(name, data):
        nonlocal off
        data = bytes(data)
        index[name] = [off, len(data)]
        blobs.append(data)
        off += len(data)
        pad = (-off) & 15
        if pad:
            blobs.append(b'\0' * pad)
            off += pad

    for b in ROM_BANKS:
        o = (b & 0x3F) << 16
        add('rom.%02X' % b, rom[o:o + 0x10000])
    stages = []
    for st in range(1, NSTAGES + 1):
        S.load_state_file(state_path('mt4_stage%02d' % st))
        S.step(0)
        w = S.wram()
        add('stage%02d' % st, bytes(S.vram()) + bytes(S.cgram()) + bytes(w[WRAM_SLICE[0]:WRAM_SLICE[1]]))
        meta = read_json(os.path.join(ASSETS, 'stages', 'stage%02d' % st, 'stage.json'))
        stages.append({
            'stage': st,
            'blob': 'stage%02d' % st,
            'layout': {'vram': [0, 0x10000], 'cgram': [0x10000, 0x200], 'wram': [0x10200, WRAM_SLICE[1] - WRAM_SLICE[0]],
                       'wram_base': WRAM_SLICE[0]},
            'ppu': S.ppu(),
            'palette_animations': meta.get('palette_animations', []),
        })
        print('stage', st, 'ok')
    with open(os.path.join(OUT, 'sb2.bin'), 'wb') as f:
        for b in blobs:
            f.write(b)
    audio = read_json(os.path.join(ASSETS, 'audio', 'audio.json'))
    manifest = {
        'version': 1,
        'note': 'generated by tools/sb2/extract/pack.py from the user ROM; do not commit',
        'bin': 'sb2.bin', 'size': off, 'blobs': index,
        'rom_banks': ['%02X' % b for b in ROM_BANKS],
        'stages': stages,
        'audio': {'music': audio.get('music', []), 'sfx': audio.get('sfx', [])},
    }
    with open(os.path.join(OUT, 'pack.json'), 'w') as f:
        json.dump(manifest, f, indent=1)
    print('wrote', os.path.join(OUT, 'sb2.bin'), off, 'bytes')


if __name__ == '__main__':
    main()
