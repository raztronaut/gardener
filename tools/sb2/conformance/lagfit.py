"""Fit the pacing model (public/arcade/sb2/pacing.js) to the original's measured cycles.

    python3 tools/sb2/re/lagcost.py                  # harness: per-tick cycles of every vector
    node tools/sb2/conformance/lagdata.mjs           # port: per-tick model inputs, paired
    python3 tools/sb2/conformance/lagfit.py          # -> public/arcade/sb2/pacing_coef.js
    python3 tools/sb2/conformance/lagfit.py --loo    # + leave-one-vector-out validation
    node tools/sb2/conformance/lagcheck.mjs          # end-to-end check of the JS model

work  = W  . x(tick)       master cycles from the end of the wait to the wait (C0FB23..C0FB18)
nmi   = WN . x(tick - 1)   master cycles of the NMI that starts the tick
Both by ridge least squares on standardised inputs (lambda 1; the weights are only used
as dot products, so the ridge only settles collinear inputs). Ticks longer than 20 frames
are left out (none in play). The frame rule (pacing.js): frames = floor((nmi + work) /
357368) + 1.
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
D = os.path.join(ROOT, 'data', 'sb2', 're', 'lagfit')
OUT = os.path.join(ROOT, 'public', 'arcade', 'sb2', 'pacing_coef.js')
FRAME = 262 * 1364
LAM = 1.0


def load():
    out = {}
    for f in sorted(os.listdir(D)):
        d = json.load(open(os.path.join(D, f)))
        R = d['rows']
        out[d['name']] = dict(
            X=np.array([r['f'] for r in R], float), y=np.array([r['work'] for r in R], float),
            so=np.array([np.nan if r['startOff'] is None else r['startOff'] for r in R], float),
            frame=np.array([r['frame'] for r in R]), names=d['names'])
    return out


def ridge(X, y, lam=LAM):
    """ridge on standardised columns; constant columns (acc0: the same 14 accesses every
    tick) are the intercept and are not penalised, so an unseen stage falls back to it"""
    sd = X.std(0)
    const = (sd == 0) & (np.abs(X).max(0) > 0)
    sc = np.where(sd == 0, np.abs(X).max(0) + 1e-9, sd)
    Xs = X / sc
    pen = np.where(const, 0.0, lam)
    return np.linalg.solve(Xs.T @ Xs + np.diag(pen), Xs.T @ y) / sc


def fit(d, exclude=()):
    vs = [v for n, v in d.items() if n not in exclude]
    X = np.vstack([v['X'] for v in vs])
    y = np.concatenate([v['y'] for v in vs])
    keep = y < 20 * FRAME
    w = ridge(X[keep], y[keep])
    P, S = [], []
    for v in vs:
        for k in range(1, len(v['X'])):
            if np.isfinite(v['so'][k]) and v['frame'][k] - v['frame'][k - 1] == 1:
                P.append(v['X'][k - 1])
                S.append(v['so'][k])
    P, S = np.array(P), np.array(S)
    wn = ridge(P, S)
    r = y - X @ w
    return w, wn, dict(rmse=float(r[keep].std()), rmse_play=float(r[y < FRAME].std()),
                       nmi_rmse=float((S - P @ wn).std()), ticks=int(keep.sum()))


def frames(v, w, wn):
    """predicted frames per tick (the frame rule), aligned with the actual gaps"""
    pw = v['X'] @ w
    pn = np.maximum(20000, v['X'] @ wn)
    nmi = np.r_[26270, pn[:-1]]
    pred = np.clip(np.floor((nmi + pw) / FRAME) + 1, 1, 12)
    act = np.r_[np.nan, np.diff(v['frame'])]
    return pred, act


def report(d, w, wn, names=None):
    rows = []
    for n, v in d.items():
        if names and n not in names:
            continue
        pred, act = frames(v, w, wn)
        m = np.isfinite(act) & (act < 20)       # skip the scoreboard gap of round_win
        a, p = act[m], pred[m]
        rows.append((n, int(m.sum()), int(a.sum()), int(p.sum()), float((a == p).mean() * 100)))
    return rows


def main():
    d = load()
    w, wn, st = fit(d)
    names = next(iter(d.values()))['names']
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by tools/sb2/conformance/lagfit.py from the harness cycle measurements\n')
        fh.write('// (tools/sb2/re/lagcost.py) and the port\'s model inputs (lagdata.mjs). Do not edit.\n')
        fh.write('// work = W . x (master cycles), nmi of the next tick = WN . x; x = pacing.js FEATURE_NAMES:\n')
        fh.write('// ' + ' '.join(names) + '\n')
        fh.write('// fit: %d ticks, rmse %.0f cycles (%.0f in play), NMI rmse %.0f\n' % (
            st['ticks'], st['rmse'], st['rmse_play'], st['nmi_rmse']))
        fh.write('export const W = [%s];\n' % ', '.join('%.6g' % x for x in w))
        fh.write('export const WN = [%s];\n' % ', '.join('%.6g' % x for x in wn))
    print('wrote', OUT, st)
    print('%-22s %6s %7s %7s %8s %7s' % ('vector', 'ticks', 'frames', 'pred', 'speed%', 'match%'))
    tot = [0, 0, 0]
    for n, T, A, P, mt in report(d, w, wn):
        tot[0] += T; tot[1] += A; tot[2] += P
        print('%-22s %6d %7d %7d %+8.2f %7.2f' % (n, T, A, P, (A - P) / A * 100, mt))
    print('ALL %d ticks, %d frames, predicted %d (%+.3f %%)' % (tot[0], tot[1], tot[2], (tot[1] - tot[2]) / tot[1] * 100))
    if '--loo' in sys.argv:
        print('leave-one-vector-out (vectors > 500 ticks):')
        for n in [k for k, v in d.items() if len(v['y']) > 500]:
            w2, wn2, _ = fit(d, exclude=(n,))
            (_, T, A, P, mt), = report(d, w2, wn2, [n])
            print('  %-22s speed %+6.2f %%  match %6.2f %%' % (n, (A - P) / A * 100, mt))


if __name__ == '__main__':
    main()
