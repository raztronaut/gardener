"""Generate public/arcade/sb2/core/layout_data.js: the 10 battle stage maps as the
original's round init leaves them before the random soft-block removal (C0F601 map
decode + C0F5AF), i.e. collision grid ($7FC000), underlay ($7FD000), BG tile words
($7FA000) and underlay tile words ($7FB000) for cells cols 0..16 x rows 0..17. Every
other cell is $C5 / tile 0. Source: capstages.py --nosoft (ROM with $C5EA4D zeroed).
Only map codes / metatile ids — no graphics.
    python3 gen_layout.py
"""
import os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
d = np.load(os.path.join(ROOT, 'data', 'sb2', 'conformance', 'init', 'stages_nosoft_0.npz'))
IDS = [0, 1, 2, 5, 6, 7, 8, 9, 0xA, 0xB]
R0, R1, C1 = 0, 18, 17
out = ['// GENERATED by tools/sb2/conformance/gen_layout.py — the 10 battle stage maps before',
       '// the random soft-block removal: per stage id, rows 0..17 x cols 0..16 of the grid',
       '// ($7FC000) and underlay ($7FD000) as 2 hex digits per cell, and of the BG tile words',
       '// ($7FA000) and underlay tile words ($7FB000) as 4 hex digits. Outside: $C5 / 0.',
       'export const STAGE_MAPS = {']
for k, sid in enumerate(IDS):
    w = d['wram'][k]
    assert int(w[0x1A]) == sid, (k, w[0x1A])
    g = w[0x1C000:0x1D000].view('<u2').reshape(32, 64)
    u = w[0x1D000:0x1E000].view('<u2').reshape(32, 64)
    t = w[0x1A000:0x1A800].view('<u2').reshape(32, 32)
    tb = w[0x1B000:0x1B800].view('<u2').reshape(32, 32)
    for arr, fill in ((g, 0xC5), (u, 0xC5)):
        m = arr.copy(); m[R0:R1, :C1] = fill
        assert (m == fill).all() and (arr >> 8).max() == 0
    for arr in (t, tb):
        m = arr.copy(); m[R0:R1, :C1] = 0
        assert (m == 0).all()
    out.append('  %d: {' % sid)
    for name, arr, f in (('grid', g, '%02X'), ('under', u, '%02X'), ('tile', t, '%04X'), ('tileUnder', tb, '%04X')):
        out.append('    %s: [' % name)
        for r in range(R0, R1):
            out.append("      '%s'," % ''.join(f % int(arr[r, c]) for c in range(C1)))
        out.append('    ],')
    out.append('  },')
out.append('};')
p = os.path.join(ROOT, 'public', 'arcade', 'sb2', 'core', 'layout_data.js')
open(p, 'w').write('\n'.join(out) + '\n')
print(p, os.path.getsize(p))
