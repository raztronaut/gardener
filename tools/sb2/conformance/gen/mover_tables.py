"""Generate public/arcade/sb2/core/movers_tables.js: the motion scripts (per-tick
velocity sequences) that the original uses for thrown / bouncing bombs and flying
items, plus the small direction tables the mover code reads. Rule data only (numbers),
read from the user's ROM:  python3 tools/sb2/conformance/gen/mover_tables.py
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
rom = open(os.path.join(ROOT, 'data', 'roms', 'Super Bomberman 2 (USA).sfc'), 'rb').read()
def o(a): return ((a >> 16) & 0x3f) << 16 | (a & 0xffff)
def w(a): x = o(a); return rom[x] | rom[x + 1] << 8
def p24(a): x = o(a); return rom[x] | rom[x + 1] << 8 | rom[x + 2] << 16

ptr = {}      # pointer-table address -> 24-bit value
scripts = {}  # script start -> list of (flags, vx, vy)
for top in (0xC5CAA0, 0xC5C9B0, 0xC5C0B6):
    for n in range(6):
        t = p24(top + 4 * n)
        ptr[top + 4 * n] = t
        for f in (2, 4, 8, 16):
            s = p24(t + 2 * f)
            ptr[t + 2 * f] = s
            a = s
            while w(a) != 0xFFFF:
                a += 6
            scripts[s] = a
# merge into address ranges
words = {}
for s, e in scripts.items():
    for a in range(s, e + 2, 2):
        words[a] = w(a)
def tbl(a, n, size=2): return [w(a + size * i) if size == 2 else rom[o(a) + i] for i in range(n)]
out = ['// GENERATED by tools/sb2/conformance/gen/mover_tables.py — mover rule data (numbers).',
       '// Motion scripts: words at ROM addresses; a script is (flags, vx, vy) words per tick,',
       '// ended by $FFFF. MPTR maps the pointer-table entries the code reads (3-byte pointers).',
       'export const MWORDS = new Map([' + ','.join('[%d,%d]' % (a, v) for a, v in sorted(words.items())) + ']);',
       'export const MPTR = new Map([' + ','.join('[%d,%d]' % (a, v) for a, v in sorted(ptr.items())) + ']);']
def emit(name, a, n, size=2):
    out.append('export const %s = [%s]; // $%06X' % (name, ','.join(str(x) for x in tbl(a, n, size)), a))
emit('DIRBITS_C5FAE7', 0xC5FAE7, 17)
emit('RANDDIR_C5FC6D', 0xC5FC6D, 16)
emit('ANIM_C5FC29', 0xC5FC29, 32)
emit('DIST_C5EE0F', 0xC5EE0F, 16)
emit('DROPN_C5EDFF', 0xC5EDFF, 16, 1)
emit('HOP_C5EB09', 0xC5EB09, 40)
emit('ANIM_C5EAE5', 0xC5EAE5, 17)
emit('REVDIR_C5FAB5', 0xC5FAB5, 17)
emit('RUBDIR_C5ECBF', 0xC5ECBF, 17)
emit('DELTA_C5E392', 0xC5E392, 9)
emit('DIRS_C5E3A4', 0xC5E3A4, 9)
emit('ANIM_C5EE41', 0xC5EE41, 17)
emit('ANIM_C5EE2F', 0xC5EE2F, 17)
emit('DROPK_C5EDDD', 0xC5EDDD, 16)
open(os.path.join(ROOT, 'public', 'arcade', 'sb2', 'core', 'movers_tables.js'), 'w').write('\n'.join(out) + '\n')
print(len(words), 'script words', len(ptr), 'pointers')
