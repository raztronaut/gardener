"""Decode the object animation scripts (C0249D interpreter) reachable from the anim-set
tables $C201A5 (script pointer tables) / $C201CD (anim-id offset tables) into a compact
op list for the JS core: public/arcade/sb2/core/animdata.js.

Ops (one per script word, keyed by its ROM address so the core keeps the original's
+70 script pointer):
  [addr, 'pose', ptr]            6xxx  +79..+7B = pose pointer (sprite frame id)
  [addr, 'wait', n]              1nnn  +0C = n ($FFF = end), stop until it runs out
  [addr, 'nop']                  0xxx / 3xxx
  [addr, 'vel', w]               2xxx  flags/velocity command (see anim.js)
  [addr, 'jump', target]         40xx
  [addr, 'call', target]         41xx
  [addr, 'ret']                  42xx
  [addr, 'loop', count]          43nn
  [addr, 'next']                 44xx
  [addr, 'set', [5 words]|null]  45nn
  [addr, 'stop']                 46xx / 5xxx
python3 gen_animdata.py   (needs the ROM)
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
rom = open(os.path.join(ROOT, 'data', 'roms', 'Super Bomberman 2 (USA).sfc'), 'rb').read()
def off(a): return ((a >> 16) & 0x3F) << 16 | (a & 0xFFFF)
def b(a): return rom[off(a)]
def w(a): return b(a) | b(a + 1) << 8
def l(a): return w(a) | b(a + 2) << 16

NSETS = 10
sets = []
for s in range(NSETS):
    base = l(0xC201A5 + 4 * s)
    offt = l(0xC201CD + 4 * s)
    sets.append((base, offt))

ops = {}
entries = {}     # (set, animoffset) -> script addr
def walk(a):
    stack = [a]
    while stack:
        a = stack.pop()
        while a not in ops:
            x = w(a)
            n = x >> 12
            if n in (0, 3):
                ops[a] = ['nop']; a += 2
            elif n == 1:
                ops[a] = ['wait', x & 0xFFF]; a += 2
            elif n == 2:
                ops[a] = ['vel', x]; a += 2
            elif n == 4:
                sub = (x >> 8) & 0xF
                if sub == 0:
                    t = l(a + 2); ops[a] = ['jump', t]; stack.append(t); break
                elif sub == 1:
                    t = l(a + 2); ops[a] = ['call', t]; stack.append(t); a += 5
                elif sub == 2:
                    ops[a] = ['ret']; break
                elif sub == 3:
                    ops[a] = ['loop', x & 0xFF]; a += 2
                elif sub == 4:
                    ops[a] = ['next']; a += 2
                elif sub == 5:
                    if x & 0xFF:
                        ops[a] = ['set', [w(a + 2 + 2 * k) for k in range(5)]]; a += 12
                    else:
                        ops[a] = ['set', None]; a += 2
                else:
                    ops[a] = ['stop']; break
            elif n == 5:
                ops[a] = ['stop']; break
            elif n == 6:
                ops[a] = ['pose', l(a + 2) & 0xFFFF | (a & 0xFF0000)]; a += 4
            else:
                ops[a] = ['bad', x]; break

for s, (base, offt) in enumerate(sets):
    for k in range(0, 0x80, 2):
        o = w(offt + k)
        sp = (offt & 0xFF0000) | w((base & 0xFF0000) | ((base + o) & 0xFFFF))
        entries[(s, k)] = sp
        walk(sp)

out = []
out.append('// GENERATED by tools/sb2/conformance/gen_animdata.py — decoded object animation')
out.append('// scripts (control flow + timing + pose ids) for the C0249D interpreter in anim.js.')
out.append('// SETS[set] = [scriptTableBase, animOffsetTable] (24-bit addresses, as in +76..+78);')
out.append('// ENTRY[set][animOffset/2] = script address; OPS = { addr: op } (see gen_animdata.py).')
out.append('export const SETS = %s;' % json.dumps([[a, c] for a, c in sets]))
out.append('export const ENTRY = %s;' % json.dumps([[entries[(s, k)] for k in range(0, 0x80, 2)] for s in range(NSETS)]))
out.append('export const OPS = {')
for a in sorted(ops):
    out.append('  %d: %s,' % (a, json.dumps(ops[a])))
out.append('};')
dst = os.path.join(ROOT, 'public', 'arcade', 'sb2', 'core', 'animdata.js')
open(dst, 'w').write('\n'.join(out) + '\n')
bad = [a for a in ops if ops[a][0] == 'bad']
print(len(ops), 'ops', 'bad:', ['%06X' % a for a in bad][:10])
