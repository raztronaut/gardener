def frame_tile():
    """the tag: border colour 15 (flashing) around a dark green inside with a soft
    inner bevel"""
    img = blank(16, 16, BG_D)
    for y in range(16):
        for x in range(16):
            if x in (0, 15) or y in (0, 15):
                img[y, x] = BORDER[0]
            elif x == 1 or y == 1:
                img[y, x] = BG_L
            elif (x + y) % 2 == 0 and x < 6 and y < 6:
                img[y, x] = BG_L
    for (x, y) in ((0, 0), (15, 0), (0, 15), (15, 15)):
        img[y, x] = BG_D
    return img


def icon(name):
    g = ICONS.get(name)
    if g is None:
        return None
    t = frame_tile()
    over(t, grid(g.replace(' ', '.'), IL), 1, 1)
    return t


def all_items():
    out = {}
    for k in ICONS:
        out[k] = icon(k)
    for i, n in enumerate(['unknown_578', 'unknown_580', 'unknown_582', 'unknown_584']):
        t = frame_tile()
        over(t, grid(GROW[i], IL), 1, 1)
        out[n] = t
    return out
